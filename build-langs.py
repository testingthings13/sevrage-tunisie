HEAD_ATTRS = {
    "en": [('<html lang="fr">', '<html lang="en">'),
           ('content="fr_TN"', 'content="en_US"')],
    "ar": [('<html lang="fr">', '<html lang="ar" dir="rtl">'),
           ('content="fr_TN"', 'content="ar_TN"')],
}


def pattern_for(fr):
    """Une espace dans la clé accepte un retour à la ligne, une indentation
    ou une espace insécable typographique (&nbsp;) dans le source."""
    return r"(?:\s|&nbsp;)+".join(re.escape(t) for t in fr.split(" ") if t)


def build(lang, idx):
    src = SRC.read_text()
    pairs = sorted(T, key=lambda r: -len(r[0]))
    tokens = {}
    misses = 0
    for i, row in enumerate(pairs):
        fr, target = row[0], row[idx]
        tok = f"\x00{i}\x00"
        src, n = re.subn(pattern_for(fr), tok.replace("\\", "\\\\"), src)
        if n == 0:
            misses += 1
            print(f"  · introuvable, ignoré : {fr[:56]}…", file=sys.stderr)
        tokens[tok] = target
    for tok, target in tokens.items():
        src = src.replace(tok, target)
    if misses:
        print(f"  ({misses} chaîne(s) non trouvée(s))", file=sys.stderr)

    for a, b in HEAD_ATTRS[lang]:
        src = src.replace(a, b)

    # canonique et og:url propres à la langue
    src = src.replace('<link rel="canonical" href="https://sevrage-tunisie.com/">',
                      f'<link rel="canonical" href="https://sevrage-tunisie.com/{lang}.html">')
    src = src.replace('<meta property="og:url" content="https://sevrage-tunisie.com/">',
                      f'<meta property="og:url" content="https://sevrage-tunisie.com/{lang}.html">')

    # lien FR du tiroir mobile : absent de index.html (page FR courante),
    # on l'injecte pour que le français reste joignable depuis ar/en
    src = src.replace(
        '<a href="ar.html" hreflang="ar" lang="ar">العربية</a>',
        '<a href="index.html" hreflang="fr" lang="fr">Français</a>\n'
        '    <a href="ar.html" hreflang="ar" lang="ar">العربية</a>')

    # l'onglet de langue actif (retirer aussi l'aria-current nu du lien FR)
    src = (src.replace(' class="is-on" aria-current="page"', "")
              .replace(' aria-current="page"', "")
              .replace(' class="is-on"', ""))
    src = re.sub(rf'(<a href="{ "index" if lang == "fr" else lang }\.html" hreflang="{lang}"[^>]*?)>',
                 r'\1 class="is-on" aria-current="page">', src)

    out = SRC.parent / f"{lang}.html"
    out.write_text(src)
    print(f"{out.name} écrit ({len(src) // 1024} Ko)")


